// Measures per-character advance widths for each skin's fonts and writes
// src/metrics.ts. The checker uses these tables to estimate how text wraps
// without needing a browser. Re-run whenever a skin's fonts change.
//
//   node scripts/measure-fonts.mjs        (needs the playwright package)

import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import { rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
function loadPlaywright() {
  try { return require("playwright"); } catch { return require(resolve(execSync("npm root -g").toString().trim(), "playwright")); }
}
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fonts = resolve(root, "spike/media/fonts");
const FACES = {
  barlow400: ["Barlow", 400, "barlow-latin-400-normal.woff2"],
  barlow600: ["Barlow", 600, "barlow-latin-600-normal.woff2"],
  barlowCondensed600: ["Barlow Condensed", 600, "barlow-condensed-latin-600-normal.woff2"],
  plexSans400: ["IBM Plex Sans", 400, "ibm-plex-sans-latin-400-normal.woff2"],
  plexSans600: ["IBM Plex Sans", 600, "ibm-plex-sans-latin-600-normal.woff2"],
  plexMono400: ["IBM Plex Mono", 400, "ibm-plex-mono-latin-400-normal.woff2"],
};
const css = Object.values(FACES).map(([family, weight, file]) =>
  `@font-face { font-family: "${family}"; font-weight: ${weight}; src: url("media/fonts/${file}") format("woff2"); }`).join("\n");

const { chromium } = loadPlaywright();
const browser = await chromium.launch();
const page = await browser.newPage();
// Fonts load only from a file page in the same tree, so write a scratch page next to them.
const scratch = resolve(fonts, "../../.measure-fonts.html");
writeFileSync(scratch, `<!doctype html><style>${css}</style>${Object.values(FACES).map(([f, w]) => `<span style="font: ${w} 20px '${f}'">x</span>`).join("")}`);
await page.goto(pathToFileURL(scratch).href);
await page.evaluate(() => document.fonts.ready);
rmSync(scratch);
const missing = await page.evaluate(faces => Object.values(faces).filter(([f, w]) => !document.fonts.check(`${w} 20px "${f}"`)).map(([f, w]) => `${f} ${w}`), FACES);
if (missing.length) { console.error("fonts failed to load:", missing); process.exit(1); }
const tables = await page.evaluate(faces => {
  const ctx = document.createElement("canvas").getContext("2d");
  const out = {};
  for (const [key, [family, weight]] of Object.entries(faces)) {
    ctx.font = `${weight} 1000px "${family}"`;
    const widths = [];
    for (let c = 32; c < 127; c++) widths.push(Math.round(ctx.measureText(String.fromCharCode(c)).width) / 1000);
    out[key] = widths;
  }
  return out;
}, FACES);
await browser.close();

const body = Object.entries(tables).map(([k, w]) => `  ${k}: [${w.join(", ")}],`).join("\n");
writeFileSync(resolve(root, "src/metrics.ts"), `// Generated by scripts/measure-fonts.mjs. Do not edit by hand.
// Advance widths in em for printable ASCII (codes 32 to 126), per font face.

export const FACE_WIDTHS: Record<string, readonly number[]> = {
${body}
};
`);
console.log("wrote src/metrics.ts:", Object.keys(tables).join(", "));
