// Bundles the browser engine (src/runtime) into runtime/pathway.js, which every
// built deck carries inline. The bundle is committed, so building a deck needs
// no bundler; CI checks it's current.
//
//   node scripts/bundle.mjs           write runtime/pathway.js
//   node scripts/bundle.mjs --check   exit 1 if it's out of date

import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "runtime/pathway.js");
const result = await build({
  entryPoints: [resolve(root, "src/runtime/main.ts")],
  bundle: true,
  format: "iife",
  target: ["es2022"],
  write: false,
  legalComments: "none",
  charset: "utf8",
  banner: { js: "// Pathway's engine. Generated by scripts/bundle.mjs from src/runtime/; do not edit." },
});
const code = result.outputFiles[0].text;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch { /* missing */ }
  if (current !== code) {
    console.error("runtime/pathway.js is out of date. Run: npm run bundle");
    process.exit(1);
  }
  console.log("runtime/pathway.js is current.");
} else {
  writeFileSync(out, code);
  console.log(`Wrote runtime/pathway.js (${(code.length / 1024).toFixed(1)} KB).`);
}
